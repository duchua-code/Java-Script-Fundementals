// Relational  or comparison operators 

// > = greater than 
// < = less than 
// >= - greater than or equal to
// <= - less than or equal to

var result = 10 > 5 

console.log(result); // This will print true because 10 is greater than 5

// equalit operators 
 var x = 1; 

 console.log(x == '1'); // This will print true because x is equal to 1\
 console.log(x === '1'); // This will print false because x is equal to 1 but they are not of the same type